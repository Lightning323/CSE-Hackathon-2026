using Godot;
using GridQuest.GameGenerator;
using GridQuest.GameGenerator.Llm;
using System;
using System.Text.Json;
using System.Threading.Tasks;

public partial class LlmHelloTest : Node
{
	public override async void _Ready()
	{
		try
		{
			var settings = LlmSettingsStore.Load();
			GD.Print($"[LLM] Provider: {settings.Provider}");
			GD.Print($"[LLM] Base URL: {settings.BaseUrl}");
			GD.Print($"[LLM] Model: {settings.Model}");

			var api = new LlmApi();
			AddChild(api);

			GD.Print("[LLM] Generating a campaign...");
			var campaign = await StoryGenerator.GenerateCampaignAsync(
				"Test Campaign",
				"A short test campaign generated by the LLM.",
				api);
			GD.Print("[LLM] Campaign:");
			GD.Print(JsonSerializer.Serialize(campaign, new JsonSerializerOptions { WriteIndented = true }));

			

			api.QueueFree();
			GetTree().Quit();
		}
		catch (Exception e)
		{
			GD.PushError($"[LLM] Test failed: {e}");
			GD.PrintErr($"[LLM] Test failed: {e.Message}");
			GetTree().Quit(1);
		}
	}
}
